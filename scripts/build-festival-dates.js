// Generate regular lunar festival dates offline using Node ICU in Asia/Shanghai.
const fs=require('fs');
const fmt=new Intl.DateTimeFormat('en-u-ca-chinese',{timeZone:'Asia/Shanghai',month:'numeric',day:'numeric'});
const result={spring:[],lantern:[],dragonboat:[],midautumn:[]};
for(let year=2020;year<=2100;year++){
 const hits={spring:[],lantern:[],dragonboat:[],midautumn:[]};
 for(let t=Date.UTC(year,0,1,4);t<Date.UTC(year+1,0,1,4);t+=86400000){
  const v=Object.fromEntries(fmt.formatToParts(new Date(t)).map(p=>[p.type,p.value]));
  const k=({'1-1':'spring','1-15':'lantern','5-5':'dragonboat','8-15':'midautumn'})[v.month+'-'+v.day];
  if(k)hits[k].push(new Date(t).toISOString().slice(0,10));
 }
 for(const k of Object.keys(hits)){if(hits[k].length!==1)throw Error(year+' '+k+' '+hits[k]);result[k].push(hits[k][0]);}
}
fs.writeFileSync('utils/festival-dates.js','// Regular lunar festival dates 2020–2100, generated by scripts/build-festival-dates.js.\nmodule.exports='+JSON.stringify(result)+';\n');
console.log(Object.fromEntries(Object.entries(result).map(([k,v])=>[k,v[6]])));
